SELECT
    (SELECT COUNT(*) FROM TLFALIQIBS) AS QTD_TLFALIQIBS,
    (SELECT COUNT(*) FROM TLFALIQCBS) AS QTD_TLFALIQCBS,
    (SELECT COUNT(*) FROM TLFCLASTRIBIC) AS QTD_TLFCLASTRIBIC,
    (SELECT COUNT(*) FROM TGFPRO WHERE GRUPOIBSCBS IS NOT NULL) AS QTD_PRODUTOS_COM_GRUPO,
    (SELECT COUNT(DISTINCT GRUPOIBSCBS) FROM TGFPRO WHERE GRUPOIBSCBS IS NOT NULL) AS QTD_GRUPOS_DISTINTOS_EM_USO
FROM DUAL
