SELECT
    TO_CHAR(ICM.IDALIQ) AS IDALIQ,
    TO_CHAR(ICM.CODTAB) AS CODTAB,
    TO_CHAR(ICM.SEQUENCIA) AS SEQUENCIA,
    TO_CHAR(ICM.TIPRESTRICAO) AS TIPRESTRICAO,
    TO_CHAR(ICM.CODRESTRICAO) AS CODRESTRICAO,
    TO_CHAR(ICM.TIPRESTRICAO2) AS TIPRESTRICAO2,
    TO_CHAR(ICM.CODRESTRICAO2) AS CODRESTRICAO2,
    UFO.UF AS UFORIGEM,
    UFD.UF AS UFDESTINO,
    TO_CHAR(ICM.ALIQUOTA) AS ALIQUOTA,
    TO_CHAR(ICM.ALIQSUBTRIB) AS ALIQSUBTRIB,
    TO_CHAR(ICM.ALIQINTDEST) AS ALIQINTDEST,
    TO_CHAR(ICM.MARGLUCRO) AS MARGLUCRO,
    TO_CHAR(ICM.MARGLUCROEST) AS MARGLUCROEST,
    TO_CHAR(ICM.MVASTUFDEST) AS MVASTUFDEST,
    TO_CHAR(ICM.MVAORIGINAL) AS MVAORIGINAL,
    TO_CHAR(ICM.MVASIMPLIFICADO) AS MVASIMPLIFICADO,
    TO_CHAR(ICM.CALCMVAAJUSTADO) AS CALCMVAAJUSTADO,
    TO_CHAR(ICM.CALCSTEXTRANOTA) AS CALCSTEXTRANOTA,
    TO_CHAR(ICM.CONSPMVABCICM) AS CONSPMVABCICM,
    TO_CHAR(ICM.CODFORMVA) AS CODFORMVA,
    TO_CHAR(ICM.PAUTAVLRSTFIXO) AS PAUTAVLRSTFIXO,
    TO_CHAR(ICM.REDBASEST) AS REDBASEST,
    TO_CHAR(ICM.DTINICIOVIGENCIA, 'YYYY-MM-DD') AS DTINICIOVIGENCIA,
    TO_CHAR(ICM.DTFIMVIGENCIA, 'YYYY-MM-DD') AS DTFIMVIGENCIA
FROM TGFICM ICM
LEFT JOIN TSIUFS UFO ON UFO.CODUF = ICM.UFORIG
LEFT JOIN TSIUFS UFD ON UFD.CODUF = ICM.UFDEST
WHERE
    (
        TO_CHAR(ICM.IDALIQ) = '2512'
    )
    OR (
        TO_CHAR(ICM.TIPRESTRICAO) = 'I'
        AND TO_CHAR(ICM.CODRESTRICAO) = '98'
        AND UFO.UF = 'SP'
        AND UFD.UF = 'SP'
    )
ORDER BY ICM.IDALIQ DESC