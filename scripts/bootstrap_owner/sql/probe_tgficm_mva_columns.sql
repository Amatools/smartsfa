SELECT
    UTC.COLUMN_NAME,
    UTC.DATA_TYPE,
    UTC.DATA_LENGTH,
    UTC.DATA_PRECISION,
    UTC.DATA_SCALE
FROM USER_TAB_COLUMNS UTC
WHERE
    UTC.TABLE_NAME = 'TGFICM'
    AND (
        UTC.COLUMN_NAME LIKE '%MVA%'
        OR UTC.COLUMN_NAME LIKE '%MARG%'
        OR UTC.COLUMN_NAME LIKE '%STUFDEST%'
    )
ORDER BY UTC.COLUMN_NAME