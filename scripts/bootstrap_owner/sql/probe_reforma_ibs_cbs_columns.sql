SELECT
    UTC.TABLE_NAME,
    UTC.COLUMN_NAME,
    UTC.DATA_TYPE,
    UTC.DATA_LENGTH,
    UTC.DATA_PRECISION,
    UTC.DATA_SCALE
FROM USER_TAB_COLUMNS UTC
WHERE
    UTC.COLUMN_NAME LIKE '%IBS%'
    OR UTC.COLUMN_NAME LIKE '%CBS%'
    OR UTC.COLUMN_NAME LIKE '%CLASSTRIB%'
    OR UTC.COLUMN_NAME LIKE '%SELETIV%'
    OR UTC.COLUMN_NAME LIKE '%REFORMA%'
ORDER BY UTC.TABLE_NAME, UTC.COLUMN_NAME
