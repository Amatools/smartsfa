SELECT
    TO_CHAR(ICM.IDALIQ) AS IDALIQ,
    UFO.UF AS UFORIGEM,
    UFD.UF AS UFDESTINO,
    TO_CHAR(ICM.TIPRESTRICAO) AS TIPRESTRICAO,
    TO_CHAR(ICM.CODRESTRICAO) AS CODRESTRICAO,
    TO_CHAR(ICM.MARGLUCRO) AS MARGLUCRO,
    TO_CHAR(ICM.MVASTUFDEST) AS MVASTUFDEST,
    TO_CHAR(ICM.MARGLUCROEST) AS MARGLUCROEST,
    CASE
      WHEN NVL(TRIM(TO_CHAR(ICM.MARGLUCRO)), 'N') NOT IN ('N', '0', '0,0', '0,00', '0.0', '0.00') THEN TO_CHAR(ICM.MARGLUCRO)
      WHEN NVL(TRIM(TO_CHAR(ICM.MVASTUFDEST)), 'N') NOT IN ('N', '0', '0,0', '0,00', '0.0', '0.00') THEN TO_CHAR(ICM.MVASTUFDEST)
      WHEN NVL(TRIM(TO_CHAR(ICM.MARGLUCROEST)), 'N') NOT IN ('N', '0', '0,0', '0,00', '0.0', '0.00') THEN TO_CHAR(ICM.MARGLUCROEST)
      ELSE '0'
    END AS MVA_EFFECTIVE
FROM TGFICM ICM
LEFT JOIN TSIUFS UFO ON UFO.CODUF = ICM.UFORIG
LEFT JOIN TSIUFS UFD ON UFD.CODUF = ICM.UFDEST
WHERE TO_CHAR(ICM.IDALIQ) = '2512'