WITH ICM_BASE AS (
    SELECT
        ICM.ROWID AS ICM_ROWID,
        ICM.*
    FROM TGFICM ICM
    WHERE ICM.DTINICIOVIGENCIA IS NULL
       OR ICM.DTINICIOVIGENCIA <= SYSDATE
),
MAPEAMENTO AS (
    SELECT DISTINCT
        I.ICM_ROWID,
        N.CODNCM AS NCM,
        CAST(NULL AS VARCHAR2(30)) AS CEST
    FROM ICM_BASE I
    JOIN TGFNCM N
      ON TO_CHAR(I.TIPRESTRICAO) IN ('N', '4', 'H')
     AND TO_CHAR(I.CODRESTRICAO) NOT IN ('-1', '0')
     AND LTRIM(TO_CHAR(I.CODRESTRICAO), '0') = LTRIM(REPLACE(N.CODNCM, '.', ''), '0')

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        N.CODNCM AS NCM,
        CAST(NULL AS VARCHAR2(30)) AS CEST
    FROM ICM_BASE I
    JOIN TGFNCM N
      ON TO_CHAR(I.TIPRESTRICAO2) IN ('N', '4', 'H')
     AND TO_CHAR(I.CODRESTRICAO2) NOT IN ('-1', '0')
     AND LTRIM(TO_CHAR(I.CODRESTRICAO2), '0') = LTRIM(REPLACE(N.CODNCM, '.', ''), '0')

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        P.NCM AS NCM,
        P.CODESPECST AS CEST
    FROM ICM_BASE I
    JOIN TGFPRO P
      ON TO_CHAR(I.TIPRESTRICAO) IN ('P', '1')
     AND TO_CHAR(I.CODRESTRICAO) NOT IN ('-1', '0')
     AND P.CODPROD = I.CODRESTRICAO
    WHERE TRIM(NVL(P.NCM, '')) <> ''

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        P.NCM AS NCM,
        P.CODESPECST AS CEST
    FROM ICM_BASE I
    JOIN TGFPRO P
      ON TO_CHAR(I.TIPRESTRICAO2) IN ('P', '1')
     AND TO_CHAR(I.CODRESTRICAO2) NOT IN ('-1', '0')
     AND P.CODPROD = I.CODRESTRICAO2
    WHERE TRIM(NVL(P.NCM, '')) <> ''

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        P.NCM AS NCM,
        P.CODESPECST AS CEST
    FROM ICM_BASE I
    JOIN TGFPRO P
      ON TO_CHAR(I.TIPRESTRICAO) = 'I'
     AND TO_CHAR(I.CODRESTRICAO) NOT IN ('-1', '0')
     AND NVL(P.GRUPOICMS, -1) = NVL(I.CODRESTRICAO, -2)
    WHERE TRIM(NVL(P.NCM, '')) <> ''

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        P.NCM AS NCM,
        P.CODESPECST AS CEST
    FROM ICM_BASE I
    JOIN TGFPRO P
      ON TO_CHAR(I.TIPRESTRICAO2) = 'I'
     AND TO_CHAR(I.CODRESTRICAO2) NOT IN ('-1', '0')
     AND NVL(P.GRUPOICMS, -1) = NVL(I.CODRESTRICAO2, -2)
    WHERE TRIM(NVL(P.NCM, '')) <> ''

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        P.NCM AS NCM,
        P.CODESPECST AS CEST
    FROM ICM_BASE I
    JOIN TGFPRO P
      ON TO_CHAR(I.TIPRESTRICAO) = 'K'
     AND TO_CHAR(I.CODRESTRICAO) NOT IN ('-1', '0')
     AND NVL(P.GRUPOICMS2, -1) = NVL(I.CODRESTRICAO, -2)
    WHERE TRIM(NVL(P.NCM, '')) <> ''

    UNION ALL

    SELECT DISTINCT
        I.ICM_ROWID,
        P.NCM AS NCM,
        P.CODESPECST AS CEST
    FROM ICM_BASE I
    JOIN TGFPRO P
      ON TO_CHAR(I.TIPRESTRICAO2) = 'K'
     AND TO_CHAR(I.CODRESTRICAO2) NOT IN ('-1', '0')
     AND NVL(P.GRUPOICMS2, -1) = NVL(I.CODRESTRICAO2, -2)
    WHERE TRIM(NVL(P.NCM, '')) <> ''
)
SELECT
    (SELECT COUNT(*) FROM ICM_BASE) AS LINHAS_ICM,
    COUNT(*) AS LINHAS_MAPEADAS,
    COUNT(DISTINCT ICM_ROWID) AS LINHAS_ICM_COM_NCM,
    COUNT(DISTINCT NCM) AS NCM_DISTINTOS,
    COUNT(DISTINCT CEST) AS CEST_DISTINTOS
FROM MAPEAMENTO
