SELECT
    NVL(TOP.CALCDIFALPART, 'N') AS TOP_CALCDIFALPART,
    COUNT(*) AS TOTAL_ITENS,
    SUM(CASE WHEN NVL(DIN.BASEDIFAL, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_BASEDIFAL,
    SUM(CASE WHEN NVL(DIN.VLRDIFALDEST, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_DIFAL_DEST,
    SUM(CASE WHEN NVL(DIN.PERCPARTDIFAL, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_PERCPART
FROM TGFDIN DIN
JOIN TGFCAB CAB
  ON CAB.NUNOTA = DIN.NUNOTA
LEFT JOIN TGFTOP TOP
  ON TOP.CODTIPOPER = CAB.CODTIPOPER
 AND TOP.DHALTER = CAB.DHTIPOPER
WHERE CAB.DTNEG >= ADD_MONTHS(TRUNC(SYSDATE), -24)
GROUP BY NVL(TOP.CALCDIFALPART, 'N')
ORDER BY TOP_CALCDIFALPART