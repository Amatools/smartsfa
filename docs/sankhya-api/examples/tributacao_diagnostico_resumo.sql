SELECT
    NVL(TO_CHAR(ICM.TIPRESTRICAO), '-') AS TIPRESTRICAO,
    NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-') AS TIPRESTRICAO2,
    COUNT(*) AS TOTAL,
    SUM(
        CASE
            WHEN NVL(TO_CHAR(ICM.CODRESTRICAO), '-1') IN ('-1', '0') THEN 1
            ELSE 0
        END
    ) AS CODRESTRICAO_GENERICO,
    SUM(
        CASE
            WHEN NVL(TO_CHAR(ICM.CODRESTRICAO2), '-1') IN ('-1', '0') THEN 1
            ELSE 0
        END
    ) AS CODRESTRICAO2_GENERICO,
    SUM(
        CASE
            WHEN NVL(ICM.ALIQSUBTRIB, 0) = 0
             AND NVL(ICM.ALIQINTDEST, 0) = 0
             AND NVL(ICM.ALIQUOTA, 0) = 0
            THEN 1
            ELSE 0
        END
    ) AS LINHAS_ALIQUOTA_ZERO,
    COUNT(DISTINCT NVL(TO_CHAR(ICM.CODTRIB), '-')) AS CODTRIB_DISTINTOS,
    COUNT(DISTINCT NVL(TO_CHAR(ICM.IDALIQ), '-')) AS IDALIQ_DISTINTOS
FROM TGFICM ICM
GROUP BY
    NVL(TO_CHAR(ICM.TIPRESTRICAO), '-'),
    NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-')
ORDER BY TOTAL DESC
