SELECT
    NVL(TO_CHAR(ICM.TIPRESTRICAO), '-') AS TIPRESTRICAO,
    NVL(TO_CHAR(ICM.CODRESTRICAO), '-') AS CODRESTRICAO,
    NVL(ICM.DESCRRESTRICAO, '-') AS DESCRRESTRICAO,
    NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-') AS TIPRESTRICAO2,
    NVL(TO_CHAR(ICM.CODRESTRICAO2), '-') AS CODRESTRICAO2,
    NVL(ICM.DESCRRESTRICAO, '-') AS DESCRRESTRICAO2,
    COUNT(*) AS TOTAL
FROM TGFICM ICM
GROUP BY
    NVL(TO_CHAR(ICM.TIPRESTRICAO), '-'),
    NVL(TO_CHAR(ICM.CODRESTRICAO), '-'),
    NVL(ICM.DESCRRESTRICAO, '-'),
    NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-'),
    NVL(TO_CHAR(ICM.CODRESTRICAO2), '-'),
    NVL(ICM.DESCRRESTRICAO, '-')
ORDER BY TOTAL DESC
FETCH FIRST 120 ROWS ONLY
