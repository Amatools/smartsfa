WITH ICM_GENERICO AS (
    SELECT DISTINCT
        NVL(ICM.CODTRIB, -1) AS CODTRIB,
        NVL(ICM.IDALIQ, -1) AS IDALIQ
    FROM TGFICM ICM
    WHERE NVL(TO_CHAR(ICM.CODRESTRICAO), '-1') IN ('-1', '0')
      AND NVL(TO_CHAR(ICM.CODRESTRICAO2), '-1') IN ('-1', '0')
),
ITE_AGREGADO AS (
    SELECT
        NVL(ITE.CODTRIB, -1) AS CODTRIB,
        NVL(ITE.IDALIQICMS, -1) AS IDALIQ,
        COUNT(DISTINCT ITE.CODPROD) AS PRODUTOS_DISTINTOS
    FROM TGFITE ITE
    WHERE ITE.CODPROD IS NOT NULL
    GROUP BY
        NVL(ITE.CODTRIB, -1),
        NVL(ITE.IDALIQICMS, -1)
)
SELECT
    COUNT(*) AS CHAVES_ICM_GENERICAS,
    SUM(CASE WHEN M1.IDALIQ IS NOT NULL THEN 1 ELSE 0 END) AS MATCH_EXATO_CODTRIB_IDALIQ,
    SUM(CASE WHEN M2.IDALIQ IS NOT NULL THEN 1 ELSE 0 END) AS MATCH_APENAS_IDALIQ,
    SUM(CASE WHEN M3.CODTRIB IS NOT NULL THEN 1 ELSE 0 END) AS MATCH_APENAS_CODTRIB,
    SUM(CASE WHEN M1.IDALIQ IS NOT NULL THEN NVL(M1.PRODUTOS_DISTINTOS, 0) ELSE 0 END) AS PRODUTOS_COBERTOS_MATCH_EXATO
FROM ICM_GENERICO I
LEFT JOIN ITE_AGREGADO M1
    ON M1.CODTRIB = I.CODTRIB
   AND M1.IDALIQ = I.IDALIQ
LEFT JOIN (
    SELECT DISTINCT IDALIQ
    FROM ITE_AGREGADO
) M2
    ON M2.IDALIQ = I.IDALIQ
LEFT JOIN (
    SELECT DISTINCT CODTRIB
    FROM ITE_AGREGADO
) M3
    ON M3.CODTRIB = I.CODTRIB
