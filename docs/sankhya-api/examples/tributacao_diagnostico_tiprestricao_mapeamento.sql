WITH RESTR AS (
    SELECT
        'R1' AS LADO,
        NVL(TO_CHAR(ICM.TIPRESTRICAO), '-') AS TIPO,
        NVL(ICM.CODRESTRICAO, -1) AS COD
    FROM TGFICM ICM
    WHERE NVL(TO_CHAR(ICM.CODRESTRICAO), '-1') NOT IN ('-1', '0')

    UNION ALL

    SELECT
        'R2' AS LADO,
        NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-') AS TIPO,
        NVL(ICM.CODRESTRICAO2, -1) AS COD
    FROM TGFICM ICM
    WHERE NVL(TO_CHAR(ICM.CODRESTRICAO2), '-1') NOT IN ('-1', '0')
)
SELECT
    TIPO,
    LADO,
    COUNT(*) AS TOTAL,
    SUM(CASE WHEN EXISTS (SELECT 1 FROM TGFPRO P WHERE P.CODPROD = R.COD AND ROWNUM = 1) THEN 1 ELSE 0 END) AS MATCH_PRODUTO,
    SUM(CASE WHEN EXISTS (
        SELECT 1
        FROM TGFNCM N
        WHERE LTRIM(TO_CHAR(R.COD), '0') = LTRIM(REPLACE(N.CODNCM, '.', ''), '0')
          AND ROWNUM = 1
    ) THEN 1 ELSE 0 END) AS MATCH_NCM,
    SUM(CASE WHEN EXISTS (SELECT 1 FROM TGFPRO P WHERE NVL(P.GRUPOICMS, -1) = R.COD AND ROWNUM = 1) THEN 1 ELSE 0 END) AS MATCH_GRUPOICMS,
    SUM(CASE WHEN EXISTS (SELECT 1 FROM TGFPRO P WHERE NVL(P.GRUPOICMS2, -1) = R.COD AND ROWNUM = 1) THEN 1 ELSE 0 END) AS MATCH_GRUPOICMS2
FROM RESTR R
GROUP BY TIPO, LADO
ORDER BY TOTAL DESC, TIPO, LADO
