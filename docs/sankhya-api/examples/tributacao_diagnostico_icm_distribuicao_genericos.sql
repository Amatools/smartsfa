SELECT
    COUNT(*) AS TOTAL_LINHAS,
    COUNT(DISTINCT NVL(CODTRIB, -1)) AS CODTRIB_DISTINTOS,
    COUNT(DISTINCT NVL(IDALIQ, -1)) AS IDALIQ_DISTINTOS,
    SUM(CASE WHEN NVL(CODTRIB, -1) = 0 THEN 1 ELSE 0 END) AS CODTRIB_ZERO,
    SUM(CASE WHEN NVL(IDALIQ, -1) > 0 THEN 1 ELSE 0 END) AS COM_IDALIQ
FROM TGFICM
WHERE NVL(TO_CHAR(CODRESTRICAO), '-1') IN ('-1', '0')
  AND NVL(TO_CHAR(CODRESTRICAO2), '-1') IN ('-1', '0')
