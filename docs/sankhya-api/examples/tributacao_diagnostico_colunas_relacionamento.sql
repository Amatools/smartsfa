SELECT
    TABLE_NAME,
    COLUMN_NAME
FROM ALL_TAB_COLUMNS
WHERE TABLE_NAME IN ('TGFICM', 'TGFPRO', 'TGFPEM', 'TGFNCM', 'TGFITE', 'TGFDIN')
  AND (
    COLUMN_NAME LIKE '%NCM%'
    OR COLUMN_NAME LIKE '%CEST%'
    OR COLUMN_NAME LIKE '%TRIB%'
    OR COLUMN_NAME LIKE '%ALIQ%'
    OR COLUMN_NAME LIKE '%GRUPOICMS%'
    OR COLUMN_NAME LIKE '%CODTAB%'
    OR COLUMN_NAME LIKE '%IDALIQ%'
  )
ORDER BY TABLE_NAME, COLUMN_NAME
