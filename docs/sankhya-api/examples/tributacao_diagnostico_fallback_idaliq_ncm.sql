WITH HIST AS (
    SELECT DISTINCT
        NVL(ITE.CODTRIB, -1) AS CODTRIB,
        NVL(ITE.IDALIQICMS, -1) AS IDALIQ,
        PRO.NCM AS NCM,
        PRO.CODESPECST AS CEST
    FROM TGFITE ITE
    JOIN TGFPRO PRO
      ON PRO.CODPROD = ITE.CODPROD
    WHERE ITE.CODPROD IS NOT NULL
      AND TRIM(NVL(PRO.NCM, '')) <> ''
),
BASE AS (
    SELECT
        CASE
            WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('N', '4')
                 AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                THEN NCM1.CODNCM
            WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('N', '4')
                 AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                THEN NCM2.CODNCM
            WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('P', '1')
                 AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                THEN PRO1.NCM
            WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('P', '1')
                 AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                THEN PRO2.NCM
            ELSE NULL
        END AS NCM_DIRETO,
        CASE
            WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('P', '1')
                 AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                THEN PRO1.CODESPECST
            WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('P', '1')
                 AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                THEN PRO2.CODESPECST
            ELSE NULL
        END AS CEST_DIRETO,
        HIST.NCM AS NCM_FALLBACK,
        HIST.CEST AS CEST_FALLBACK
    FROM TGFICM ICM
    LEFT JOIN TGFPRO PRO1
      ON TO_CHAR(ICM.TIPRESTRICAO) IN ('P', '1')
     AND ICM.CODRESTRICAO = PRO1.CODPROD
    LEFT JOIN TGFPRO PRO2
      ON TO_CHAR(ICM.TIPRESTRICAO2) IN ('P', '1')
     AND ICM.CODRESTRICAO2 = PRO2.CODPROD
    LEFT JOIN TGFNCM NCM1
      ON TO_CHAR(ICM.TIPRESTRICAO) IN ('N', '4')
     AND LTRIM(TO_CHAR(ICM.CODRESTRICAO), '0') = LTRIM(REPLACE(NCM1.CODNCM, '.', ''), '0')
    LEFT JOIN TGFNCM NCM2
      ON TO_CHAR(ICM.TIPRESTRICAO2) IN ('N', '4')
     AND LTRIM(TO_CHAR(ICM.CODRESTRICAO2), '0') = LTRIM(REPLACE(NCM2.CODNCM, '.', ''), '0')
    LEFT JOIN HIST
      ON HIST.CODTRIB = NVL(ICM.CODTRIB, -1)
     AND HIST.IDALIQ = NVL(ICM.IDALIQ, -1)
    WHERE ICM.DTINICIOVIGENCIA IS NULL
       OR ICM.DTINICIOVIGENCIA <= SYSDATE
)
SELECT
    COUNT(*) AS LINHAS_RESULTANTES,
    SUM(CASE WHEN TRIM(NVL(NCM_DIRETO, '')) <> '' THEN 1 ELSE 0 END) AS COM_NCM_DIRETO,
    SUM(CASE WHEN TRIM(NVL(NCM_DIRETO, '')) = '' AND TRIM(NVL(NCM_FALLBACK, '')) <> '' THEN 1 ELSE 0 END) AS COM_NCM_SOMENTE_FALLBACK,
    SUM(CASE WHEN TRIM(NVL(COALESCE(NCM_DIRETO, NCM_FALLBACK), '')) <> '' THEN 1 ELSE 0 END) AS COM_NCM_FINAL,
    COUNT(DISTINCT COALESCE(NCM_DIRETO, NCM_FALLBACK)) AS NCM_FINAIS_DISTINTOS,
    COUNT(DISTINCT COALESCE(CEST_DIRETO, CEST_FALLBACK)) AS CEST_FINAIS_DISTINTOS
FROM BASE
