SELECT
    COUNT(*) AS TOTAL_ICM,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('N', '4', 'H')
              AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R1_NCM_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('N', '4', 'H')
              AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R2_NCM_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('P', '1')
              AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R1_PROD_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('P', '1')
              AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R2_PROD_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO) = 'I'
              AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R1_GI_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO2) = 'I'
              AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R2_GI_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO) = 'K'
              AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R1_GK_CAND,
    SUM(CASE WHEN TO_CHAR(ICM.TIPRESTRICAO2) = 'K'
              AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0') THEN 1 ELSE 0 END) AS BRANCH_R2_GK_CAND,
    SUM(CASE WHEN NCM1.CODNCM IS NOT NULL THEN 1 ELSE 0 END) AS MATCH_R1_NCM,
    SUM(CASE WHEN NCM2.CODNCM IS NOT NULL THEN 1 ELSE 0 END) AS MATCH_R2_NCM,
    SUM(CASE WHEN PRO1.NCM IS NOT NULL AND TRIM(PRO1.NCM) <> '' THEN 1 ELSE 0 END) AS MATCH_R1_PROD,
    SUM(CASE WHEN PRO2.NCM IS NOT NULL AND TRIM(PRO2.NCM) <> '' THEN 1 ELSE 0 END) AS MATCH_R2_PROD,
    SUM(CASE WHEN PRO_GI1.NCM IS NOT NULL AND TRIM(PRO_GI1.NCM) <> '' THEN 1 ELSE 0 END) AS MATCH_R1_GI,
    SUM(CASE WHEN PRO_GI2.NCM IS NOT NULL AND TRIM(PRO_GI2.NCM) <> '' THEN 1 ELSE 0 END) AS MATCH_R2_GI,
    SUM(CASE WHEN PRO_GK1.NCM IS NOT NULL AND TRIM(PRO_GK1.NCM) <> '' THEN 1 ELSE 0 END) AS MATCH_R1_GK,
    SUM(CASE WHEN PRO_GK2.NCM IS NOT NULL AND TRIM(PRO_GK2.NCM) <> '' THEN 1 ELSE 0 END) AS MATCH_R2_GK,
    SUM(
        CASE
            WHEN (
                CASE
                    WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('N', '4', 'H')
                         AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                        THEN NCM1.CODNCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('N', '4', 'H')
                         AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                        THEN NCM2.CODNCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO) IN ('P', '1')
                         AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                        THEN PRO1.NCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO2) IN ('P', '1')
                         AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                        THEN PRO2.NCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO) = 'I'
                         AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                        THEN PRO_GI1.NCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO2) = 'I'
                         AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                        THEN PRO_GI2.NCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO) = 'K'
                         AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
                        THEN PRO_GK1.NCM
                    WHEN TO_CHAR(ICM.TIPRESTRICAO2) = 'K'
                         AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
                        THEN PRO_GK2.NCM
                    ELSE NULL
                END
            ) IS NOT NULL
            THEN 1 ELSE 0
        END
    ) AS NCM_FINAL_NOT_NULL
FROM TGFICM ICM
LEFT JOIN TGFPRO PRO1
    ON TO_CHAR(ICM.TIPRESTRICAO) IN ('P', '1')
   AND ICM.CODRESTRICAO = PRO1.CODPROD
LEFT JOIN TGFPRO PRO2
    ON TO_CHAR(ICM.TIPRESTRICAO2) IN ('P', '1')
   AND ICM.CODRESTRICAO2 = PRO2.CODPROD
LEFT JOIN TGFPRO PRO_GI1
    ON TO_CHAR(ICM.TIPRESTRICAO) = 'I'
   AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
   AND NVL(PRO_GI1.GRUPOICMS, -1) = NVL(ICM.CODRESTRICAO, -2)
LEFT JOIN TGFPRO PRO_GI2
    ON TO_CHAR(ICM.TIPRESTRICAO2) = 'I'
   AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
   AND NVL(PRO_GI2.GRUPOICMS, -1) = NVL(ICM.CODRESTRICAO2, -2)
LEFT JOIN TGFPRO PRO_GK1
    ON TO_CHAR(ICM.TIPRESTRICAO) = 'K'
   AND TO_CHAR(ICM.CODRESTRICAO) NOT IN ('-1', '0')
   AND NVL(PRO_GK1.GRUPOICMS2, -1) = NVL(ICM.CODRESTRICAO, -2)
LEFT JOIN TGFPRO PRO_GK2
    ON TO_CHAR(ICM.TIPRESTRICAO2) = 'K'
   AND TO_CHAR(ICM.CODRESTRICAO2) NOT IN ('-1', '0')
   AND NVL(PRO_GK2.GRUPOICMS2, -1) = NVL(ICM.CODRESTRICAO2, -2)
LEFT JOIN TGFNCM NCM1
    ON TO_CHAR(ICM.TIPRESTRICAO) IN ('N', '4', 'H')
   AND LTRIM(TO_CHAR(ICM.CODRESTRICAO), '0') = LTRIM(REPLACE(NCM1.CODNCM, '.', ''), '0')
LEFT JOIN TGFNCM NCM2
    ON TO_CHAR(ICM.TIPRESTRICAO2) IN ('N', '4', 'H')
   AND LTRIM(TO_CHAR(ICM.CODRESTRICAO2), '0') = LTRIM(REPLACE(NCM2.CODNCM, '.', ''), '0')
WHERE ICM.DTINICIOVIGENCIA IS NULL
   OR ICM.DTINICIOVIGENCIA <= SYSDATE
