SELECT
    COUNT(*) AS TOTAL_TTKICM,
    SUM(CASE WHEN TRIM(NVL(NCM, '')) <> '' THEN 1 ELSE 0 END) AS COM_NCM,
    SUM(CASE WHEN TRIM(NVL(CESTREGRA, '')) <> '' THEN 1 ELSE 0 END) AS COM_CEST,
    COUNT(DISTINCT NVL(CODTRIB, -1)) AS CODTRIB_DISTINTOS,
    COUNT(DISTINCT NVL(UFORIG, '-')) AS UFORIG_DISTINTOS,
    COUNT(DISTINCT NVL(UFDEST, '-')) AS UFDEST_DISTINTOS
FROM TTKICM
