SELECT
    NVL(TO_CHAR(ICM.CODTRIB), '-') AS CODTRIB,
    NVL(TO_CHAR(ICM.IDALIQ), '-') AS IDALIQ,
    NVL(TO_CHAR(ICM.TIPRESTRICAO), '-') AS TIPRESTRICAO,
    NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-') AS TIPRESTRICAO2,
    COUNT(*) AS TOTAL,
    MIN(NVL(ICM.ALIQSUBTRIB, 0)) AS MIN_ALIQSUBTRIB,
    MAX(NVL(ICM.ALIQSUBTRIB, 0)) AS MAX_ALIQSUBTRIB,
    MIN(NVL(ICM.ALIQINTDEST, 0)) AS MIN_ALIQINTDEST,
    MAX(NVL(ICM.ALIQINTDEST, 0)) AS MAX_ALIQINTDEST,
    MIN(NVL(ICM.ALIQUOTA, 0)) AS MIN_ALIQUOTA,
    MAX(NVL(ICM.ALIQUOTA, 0)) AS MAX_ALIQUOTA
FROM TGFICM ICM
GROUP BY
    NVL(TO_CHAR(ICM.CODTRIB), '-'),
    NVL(TO_CHAR(ICM.IDALIQ), '-'),
    NVL(TO_CHAR(ICM.TIPRESTRICAO), '-'),
    NVL(TO_CHAR(ICM.TIPRESTRICAO2), '-')
ORDER BY TOTAL DESC
FETCH FIRST 50 ROWS ONLY
