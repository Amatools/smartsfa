SELECT
    CASE
        WHEN CAB.DTNEG IS NULL THEN 'SEM_DATA'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2016 THEN '2016'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2017 THEN '2017'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2018 THEN '2018'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) >= 2019 THEN '2019+'
        ELSE 'OUTROS'
    END AS FAIXA_ANO,

    CASE
        WHEN CAB.DTNEG IS NULL THEN NULL
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2016 THEN 40
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2017 THEN 60
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2018 THEN 80
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) >= 2019 THEN 100
        ELSE NULL
    END AS PARTILHA_DESTINO_ESPERADA,

    COUNT(*) AS TOTAL_ITENS,
    SUM(CASE WHEN NVL(DIN.BASEDIFAL, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_BASEDIFAL,
    SUM(CASE WHEN NVL(DIN.VLRDIFALDEST, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_DIFAL_DEST,
    SUM(CASE WHEN NVL(DIN.VLRDIFALREM, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_DIFAL_REM,
    SUM(CASE WHEN NVL(DIN.PERCPARTDIFAL, 0) <> 0 THEN 1 ELSE 0 END) AS ITENS_COM_PERCPART,
    SUM(CASE WHEN NVL(DIN.PERCPARTDIFAL, 0) =
        CASE
            WHEN CAB.DTNEG IS NULL THEN -1
            WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2016 THEN 40
            WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2017 THEN 60
            WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2018 THEN 80
            WHEN EXTRACT(YEAR FROM CAB.DTNEG) >= 2019 THEN 100
            ELSE -1
        END
    THEN 1 ELSE 0 END) AS ITENS_COM_PERCPART_ESPERADO,
    SUM(CASE WHEN DIN.TIPCALCDIFAL IS NOT NULL THEN 1 ELSE 0 END) AS ITENS_COM_TIPCALCDIFAL
FROM TGFDIN DIN
JOIN TGFCAB CAB ON CAB.NUNOTA = DIN.NUNOTA
WHERE CAB.DTNEG >= ADD_MONTHS(TRUNC(SYSDATE), -24)
GROUP BY
    CASE
        WHEN CAB.DTNEG IS NULL THEN 'SEM_DATA'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2016 THEN '2016'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2017 THEN '2017'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2018 THEN '2018'
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) >= 2019 THEN '2019+'
        ELSE 'OUTROS'
    END,
    CASE
        WHEN CAB.DTNEG IS NULL THEN NULL
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2016 THEN 40
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2017 THEN 60
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) = 2018 THEN 80
        WHEN EXTRACT(YEAR FROM CAB.DTNEG) >= 2019 THEN 100
        ELSE NULL
    END
ORDER BY FAIXA_ANO