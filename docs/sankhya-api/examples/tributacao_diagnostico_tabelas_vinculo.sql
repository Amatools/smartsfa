WITH C AS (
    SELECT
        TABLE_NAME,
        COLUMN_NAME
    FROM ALL_TAB_COLUMNS
)
SELECT
    TABLE_NAME,
    MAX(CASE WHEN COLUMN_NAME = 'CODTRIB' THEN 1 ELSE 0 END) AS HAS_CODTRIB,
    MAX(CASE WHEN COLUMN_NAME = 'IDALIQ' THEN 1 ELSE 0 END) AS HAS_IDALIQ,
    MAX(CASE WHEN COLUMN_NAME LIKE '%CODPROD%' THEN 1 ELSE 0 END) AS HAS_CODPROD,
    MAX(CASE WHEN COLUMN_NAME LIKE '%NCM%' THEN 1 ELSE 0 END) AS HAS_NCM,
    MAX(CASE WHEN COLUMN_NAME LIKE '%CEST%' OR COLUMN_NAME LIKE '%CODESPECST%' THEN 1 ELSE 0 END) AS HAS_CEST,
    MAX(CASE WHEN COLUMN_NAME LIKE '%GRUPOICMS%' THEN 1 ELSE 0 END) AS HAS_GRUPOICMS
FROM C
GROUP BY TABLE_NAME
HAVING MAX(CASE WHEN COLUMN_NAME = 'CODTRIB' THEN 1 ELSE 0 END) = 1
    OR MAX(CASE WHEN COLUMN_NAME = 'IDALIQ' THEN 1 ELSE 0 END) = 1
ORDER BY
    HAS_CODTRIB DESC,
    HAS_IDALIQ DESC,
    HAS_CODPROD DESC,
    HAS_NCM DESC,
    HAS_CEST DESC,
    HAS_GRUPOICMS DESC,
    TABLE_NAME
