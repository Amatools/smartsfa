SELECT
    PAR.CODPARC,
    PAR.NOMEPARC,
    PAR.RAZAOSOCIAL,
    PAR.CGC_CPF,
    PAR.TIPPESSOA,
    PAR.CLIENTE,
    PAR.ATIVO,
    PAR.IDENTINSCESTAD,
    PAR.INSCESTADNAUF,
    PAR.INSCMUN,
    PAR.CLASSIFICMS,
    PAR.CODTAB,
    PAR.CODTABST,
    PAR.CODCID,
    PAR.CEP,
    PAR.CODEND,
    PAR.NUMEND,
    PAR.COMPLEMENTO,
    PAR.CODBAI,
    PAR.TELEFONE,
    PAR.EMAIL,
    PAR.DTCAD,
    CID.NOMECID,
    CID.UF AS CODUF_CIDADE,
    UFS.UF AS SIGLA_UF
FROM TGFPAR PAR
LEFT JOIN TSICID CID ON CID.CODCID = PAR.CODCID
LEFT JOIN TSIUFS UFS ON UFS.CODUF = CID.UF
WHERE PAR.CODPARC = 191
